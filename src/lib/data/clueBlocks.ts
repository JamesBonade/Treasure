export const buildMixedCluePreview = (action: string, place: string, discover: string): string => {
	const parts = [action.trim(), place.trim()].filter(Boolean);
	const lead = parts.join(' ');
	const question = discover.trim();
	if (!lead && !question) return '';
	if (!question) return lead;
	if (!lead) return question;
	return `${lead}. ${question}`;
};
